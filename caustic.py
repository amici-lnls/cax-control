"""Utilities for caustic scans and uncertainty-aware hyperbola fitting.

The raw image returned by the Shadow helpers is only a histogram container. Its
fit metadata are generated by Histogram2DAnalyzer, and the caustic module is
responsible for scanning multiple distances, extracting sigma-widths and their
uncertainties, and fitting a hyperbola to each axis.
"""

from __future__ import annotations

from concurrent.futures import ProcessPoolExecutor
from dataclasses import dataclass

import numpy as np
from scipy.optimize import curve_fit

try:  # pragma: no cover - optional runtime dependency for notebook workflows
    from shadowpy.utils import ReferenceFrame
except Exception:  # pragma: no cover
    ReferenceFrame = None

try:
    from image_statistics import Histogram2DAnalyzer
except Exception:  # pragma: no cover
    Histogram2DAnalyzer = None

try:  # pragma: no cover
    import matplotlib.pyplot as plt
except Exception:  # pragma: no cover
    plt = None


def _safe_float(value, default=np.nan):
    try:
        out = float(value)
    except (TypeError, ValueError):
        return float(default)
    return out if np.isfinite(out) else float(default)


def hyperbola_model(distance, amplitude, focus, scale):
    """Hyperbolic dependence of the beam width on propagation distance."""
    return amplitude * np.sqrt(1.0 + ((distance - focus) / scale) ** 2)


def hyperbola_from_fit(params):
    """Return a callable that evaluates the fitted hyperbola model."""
    params = np.asarray(params, dtype=float)
    if params.size != 3:
        raise ValueError("Fit parameters must contain (amplitude, focus, scale).")

    def _model(distance):
        return hyperbola_model(distance, *params)

    return _model


def ana_from_image(image):
    """Construct a Histogram2DAnalyzer from a raw Shadow image ticket."""
    if image is None:
        raise ValueError("image must not be None.")
    if Histogram2DAnalyzer is None:
        raise RuntimeError("image_statistics.Histogram2DAnalyzer is not available.")

    histogram = np.asarray(getattr(image, "histogram", np.array([[0.0]])))
    x_edges = np.asarray(getattr(image, "bin_h_edges", np.arange(histogram.shape[0] + 1)), dtype=float)
    y_edges = np.asarray(getattr(image, "bin_v_edges", np.arange(histogram.shape[1] + 1)), dtype=float)
    return Histogram2DAnalyzer(histogram, x_bin_edges=x_edges*1000, y_bin_edges=y_edges*1000)


def fit_beam_image(image, *, useroi=True):
    """Compute moments and fit the Gaussian profile in a single image."""
    ana = ana_from_image(image)
    hprm = ana.compute_momenta(useroi=useroi)
    if hprm is None:
        return ana
    ana.fit(hprm=hprm, useroi=useroi)
    return ana


def fit_caustic_hyperbola(distances, widths, uncertainties, *,
                         initial_guess=None, bounds=None, maxfev=20000):
    """Fit the sigma-vs-distance hyperbola with uncertainty weighting."""
    distances = np.asarray(distances, dtype=float)
    widths = np.asarray(widths, dtype=float)
    uncertainties = np.asarray(uncertainties, dtype=float)

    valid = np.isfinite(distances) & np.isfinite(widths) & np.isfinite(uncertainties)
    if valid.sum() < 4:
        raise ValueError("Need at least four finite caustic points to fit the hyperbola.")

    distances = distances[valid]
    widths = widths[valid]
    uncertainties = uncertainties[valid]
    uncertainties = np.clip(uncertainties, np.finfo(float).eps, None)

    if initial_guess is None:
        amplitude = np.nanmedian(widths)
        if not np.isfinite(amplitude) or amplitude <= 0:
            amplitude = max(np.nanmax(widths), 1.0)
        focus = float(distances[np.argmin(widths)]) if widths.size else float(np.median(distances))
        scale = max(float(np.ptp(distances) / 4.0), 1e-6)
        initial_guess = (amplitude, focus, scale)

    if bounds is None:
        lower = (0.0, np.min(distances) - max(10.0, np.ptp(distances)), 1e-6)
        upper = (max(np.max(widths) * 10.0, 1.0), np.max(distances) + max(10.0, np.ptp(distances)), 1e6)
        bounds = (lower, upper)

    params, covariance = curve_fit(
        hyperbola_model,
        distances,
        widths,
        p0=initial_guess,
        sigma=uncertainties,
        bounds=bounds,
        maxfev=maxfev,
    )
    return params, covariance


@dataclass
class CausticAxisResult:
    """Result of one caustic axis (x or y)."""

    axis: str
    distances: np.ndarray
    widths: np.ndarray
    uncertainties: np.ndarray
    fit_params: np.ndarray
    covariance: np.ndarray

    @property
    def amplitude(self):
        return float(self.fit_params[0])

    @property
    def focus(self):
        return float(self.fit_params[1])

    @property
    def waist_scale(self):
        return float(self.fit_params[2])

    @property
    def min_width(self):
        return float(hyperbola_model(self.focus, *self.fit_params))

    def model(self, distance):
        return hyperbola_model(distance, *self.fit_params)

    def plot(self, ax=None, *, color=None, label=None, show_fit=True, show_errorbars=True):
        """Draw the sampled points and the fitted hyperbola for one axis."""
        if plt is None:
            raise RuntimeError("matplotlib is required for plotting.")
        if ax is None:
            _, ax = plt.subplots(figsize=(8, 4))
        if color is None:
            color = "C0" if self.axis == "x" else "C1"
        if label is None:
            label = f"{self.axis.upper()} sigma"

        if show_errorbars:
            ax.errorbar(
                self.distances,
                self.widths,
                yerr=self.uncertainties,
                fmt="o",
                markersize=4,
                lw=1.2,
                color=color,
                ecolor=color,
                alpha=0.9,
                label=label,
            )
        else:
            ax.plot(self.distances, self.widths, "o", color=color, label=label)

        if show_fit:
            z = np.linspace(np.min(self.distances), np.max(self.distances), 400)
            ax.plot(z, self.model(z), "--", color=color, lw=1.5)

        ax.axvline(self.focus, color=color, linestyle="--", linewidth=1.0,
                   alpha=0.8, label=f"focus {self.axis.upper()} = {self.focus:.3f}")

        return ax


@dataclass
class CausticResult:
    """Result of a combined x/y caustic scan."""

    x: CausticAxisResult
    y: CausticAxisResult

    @property
    def distances(self):
        return self.x.distances

    @property
    def focus_x(self):
        return self.x.focus

    @property
    def focus_y(self):
        return self.y.focus

    @property
    def focus_midpoint(self):
        return 0.5 * (self.focus_x + self.focus_y)

    @property
    def astigmatism(self):
        return abs(self.focus_y - self.focus_x)

    def model(self, axis, distance):
        axis_results = {"x": self.x, "y": self.y}
        return axis_results[axis].model(distance)

    def plot(self, ax=None, *, show_projection=True):
        """Overlay x and y caustic profiles and mark the fitted focus positions."""
        if plt is None:
            raise RuntimeError("matplotlib is required for plotting.")
        if ax is None:
            _, ax = plt.subplots(figsize=(9, 5))

        self.x.plot(ax=ax, color="C0", label="x sigma")
        self.y.plot(ax=ax, color="C1", label="y sigma")

        if show_projection:
            ymin, ymax = ax.get_ylim()
            ax.vlines(self.focus_x, ymin, ymax, colors="C0", linestyles="-.", alpha=0.7)
            ax.vlines(self.focus_y, ymin, ymax, colors="C1", linestyles="-.", alpha=0.7)
            ax.vlines(self.focus_midpoint, ymin, ymax, colors="k", linestyles="--", alpha=0.9)

        ax.set_xlabel("Distance")
        ax.set_ylabel("Sigma width")
        ax.set_title(f"Astigmatism = {self.astigmatism:.3f}")
        ax.grid(alpha=0.3)
        ax.legend()
        return ax


def _coerce_measurement(result):
    """Normalise a measurement payload to a dict with x/y sigma pairs."""
    if isinstance(result, dict):
        x = result.get("x", result.get("X"))
        y = result.get("y", result.get("Y"))
        if x is None and y is None:
            raise ValueError("Measurement dictionary must contain x/y entries.")
        if x is None:
            x = (np.nan, np.nan)
        if y is None:
            y = (np.nan, np.nan)
        return {
            "x": x,
            "y": y,
        }

    if isinstance(result, (tuple, list)) and len(result) == 4:
        return {"x": (result[0], result[1]), "y": (result[2], result[3])}

    raise TypeError("Measurement must return a dict or a 4-tuple (x_width, x_sigma, y_width, y_sigma).")


def _fit_axis_result(distances, widths, uncertainties, axis):
    distances = np.asarray(distances, dtype=float)
    widths = np.asarray(widths, dtype=float)
    uncertainties = np.asarray(uncertainties, dtype=float)

    valid = np.isfinite(distances) & np.isfinite(widths) & np.isfinite(uncertainties)
    if valid.sum() < 4:
        raise ValueError(f"At least four finite {axis} measurements are required for fitting.")

    d = distances[valid]
    w = widths[valid]
    u = uncertainties[valid]
    u = np.clip(u, 1e-8, None)
    params, covariance = fit_caustic_hyperbola(d, w, u)
    return CausticAxisResult(axis=axis, distances=d, widths=w, uncertainties=u,
                            fit_params=params, covariance=covariance)


def caustic(beam, measure, distances, *, axes=("x", "y"), max_workers=None):
    """Measure a caustic scan and fit both axes from a single pass.

    The callback should return either:
      - a dict with ``{"x": (width, sigma), "y": (width, sigma)}``
      - or a 4-tuple ``(x_width, x_sigma, y_width, y_sigma)``.
    """
    distances = np.asarray(distances, dtype=float)
    if distances.size == 0:
        raise ValueError("At least one distance is required for a caustic scan.")

    if max_workers is None or max_workers <= 1 or distances.size < 2:
        results = [measure(beam, float(d)) for d in distances]
    else:
        try:
            with ProcessPoolExecutor(max_workers=max_workers) as pool:
                results = [future.result() for future in [pool.submit(measure, beam, float(d)) for d in distances]]
        except Exception:
            results = [measure(beam, float(d)) for d in distances]

    x_distances = []
    x_widths = []
    x_errors = []
    y_distances = []
    y_widths = []
    y_errors = []

    for distance, result in zip(distances, results):
        payload = _coerce_measurement(result)
        for axis in ("x", "y"):
            width, sigma = payload[axis]
            width = _safe_float(width, np.nan)
            sigma = _safe_float(sigma, np.nan)
            if np.isfinite(width) and np.isfinite(sigma):
                if axis == "x":
                    x_distances.append(float(distance))
                    x_widths.append(float(width))
                    x_errors.append(float(sigma))
                else:
                    y_distances.append(float(distance))
                    y_widths.append(float(width))
                    y_errors.append(float(sigma))

    x = _fit_axis_result(x_distances, x_widths, x_errors, "x") if x_distances else None
    y = _fit_axis_result(y_distances, y_widths, y_errors, "y") if y_distances else None

    if x is None or y is None:
        raise ValueError("Insufficient valid measurements to fit both caustic axes.")

    return CausticResult(x=x, y=y)


def image_caustic(beam, frame, distances, *, image_size=(210, 280),
                 range_mode="robust", quantiles=(0.0001, 0.9999),
                 pad_fraction=0.10, axes=("x", "y"), max_workers=None):
    """Scan a beam at multiple distances and fit both sigma profiles."""
    if frame is None and hasattr(beam, "frame"):
        frame = beam.frame
    if frame is None:
        raise ValueError("A ReferenceFrame is required to measure a beam caustic image.")

    def measure(beam_obj, distance):
        from shadowpy.utils import image_from_beam

        beam_copy = beam_obj.duplicate()
        beam_copy.retrace(float(distance))
        image = image_from_beam(
            beam_copy,
            frame,
            image_size=image_size,
            range_mode=range_mode,
            quantiles=quantiles,
            pad_fraction=pad_fraction,
        )
        ana = ana_from_image(image)
        hprm = ana.compute_momenta()
        if hprm is None:
            return {"x": (np.nan, np.nan), "y": (np.nan, np.nan)}

        fitted = ana.fit(hprm=hprm)
        if fitted is None:
            return {"x": (np.nan, np.nan), "y": (np.nan, np.nan)}

        x_width = _safe_float(fitted.get("sigx", np.nan), np.nan)
        y_width = _safe_float(fitted.get("sigy", np.nan), np.nan)
        x_err = _safe_float(fitted.get("errors", {}).get("sigx", np.nan), np.nan)
        y_err = _safe_float(fitted.get("errors", {}).get("sigy", np.nan), np.nan)
        if not np.isfinite(x_err):
            x_err = x_width * 0.05
        if not np.isfinite(y_err):
            y_err = y_width * 0.05
        return {"x": (x_width, x_err), "y": (y_width, y_err)}

    return caustic(beam, measure, distances, axes=axes, max_workers=max_workers)
